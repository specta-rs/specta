//! Elm project discovery and the [`Elm`] exporter entrypoint.

use std::{
    fmt,
    fs::File,
    io::BufReader,
    path::{Path, PathBuf},
};

use serde_json::Value;
use specta::Types;

use crate::{
    Error,
    export::{Exporter, IntoExporter},
};

/// Comment prefix used by the Elm language.
pub(crate) const COMMENT_SYMBOL: &str = "-- ";
/// File extension of generated Elm modules.
pub(crate) const EXTENSION: &str = "elm";
/// Prefix of an Elm custom type declaration.
pub(crate) const ELM_ENUM_SYMBOL: &str = "type ";
/// Prefix of an Elm type alias declaration.
pub(crate) const ELM_STRUCT_SYMBOL: &str = "type alias ";
/// Header comment written into every generated file.
pub(crate) const PRELUDE: &str = "generated by specta-elm";
/// Keywords which cannot be used as an Elm type name.
pub(crate) const RESERVED_TYPE_NAMES: &[&str] = &[
    "if", "then", "else", "case", "of", "let", "in", "type", "module", "where", "import",
    "exposing", "as", "port",
];

/// Exports a [`Types`] collection into an Elm project.
///
/// ```ignore
/// Elm::init(types, "./frontend")?.export(exporter::SingleFile("Types"))?;
/// ```
#[derive(Debug, Clone)]
pub struct Elm {
    project: Project,
    types: Types,
}

impl Elm {
    /// Prepare an export into the Elm project rooted at `path`.
    ///
    /// `path` can be the project directory or any file/directory inside it. The
    /// project's `elm.json` is located by searching `path` and its immediate
    /// subdirectories.
    pub fn init(types: Types, path: impl AsRef<Path>) -> Result<Self, Error> {
        Ok(Self {
            project: Project::from_path(path.as_ref())?,
            types,
        })
    }

    /// Render every registered type using `output` and write the files into the project.
    pub fn export<O: IntoExporter>(&self, output: O) -> Result<(), Error> {
        output.into_exporter(&self.project)?.export(&self.types)
    }
}

/// An Elm core module which generated type names depend on.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum ElmCoreLibImport {
    /// [`Dict`](https://package.elm-lang.org/packages/elm/core/latest/Dict)
    Dict,
    /// [`Set`](https://package.elm-lang.org/packages/elm/core/latest/Set)
    Set,
}

impl fmt::Display for ElmCoreLibImport {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            ElmCoreLibImport::Dict => "Dict",
            ElmCoreLibImport::Set => "Set",
        })
    }
}

/// The Elm project generated code is written into.
#[derive(Debug, Clone)]
pub struct Project {
    src_dirs: Vec<PathBuf>,
}

impl Project {
    /// Source directories declared by the project's `elm.json`.
    pub fn source_directories(&self) -> &[PathBuf] {
        &self.src_dirs
    }

    /// Locate the Elm project which contains `path`.
    ///
    /// `path` can be the project directory or any file/directory inside it.
    fn from_path(path: &Path) -> Result<Self, Error> {
        let start = if path.is_file() {
            path.parent().unwrap_or(Path::new("."))
        } else {
            path
        };

        let elm_json_path =
            find_elm_json(start, 2).ok_or_else(|| Error::elm_json_not_found(start))?;

        let file = File::open(&elm_json_path)
            .map_err(|source| Error::read_file(elm_json_path.clone(), source))?;
        let config: Value = serde_json::from_reader(BufReader::new(file))
            .map_err(|source| Error::invalid_elm_json(elm_json_path.clone(), source))?;

        let project_dir = elm_json_path.parent().unwrap_or(Path::new("."));
        let src_dirs = config
            .get("source-directories")
            .and_then(Value::as_array)
            .map(|arr| {
                arr.iter()
                    .filter_map(Value::as_str)
                    .map(|rel_dir| project_dir.join(rel_dir))
                    .collect()
            })
            .unwrap_or_default();

        Ok(Project { src_dirs })
    }
}

fn find_elm_json(root: &Path, max_depth: usize) -> Option<PathBuf> {
    let candidate = root.join("elm.json");
    if candidate.is_file() {
        return Some(candidate);
    }
    if max_depth == 0 {
        return None;
    }

    std::fs::read_dir(root)
        .ok()?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| path.is_dir())
        .find_map(|path| find_elm_json(&path, max_depth - 1))
}
