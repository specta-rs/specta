fn rust_type_path(ndt: &NamedDataType) -> Cow<'static, str> {
    if ndt.module_path.is_empty() {
        ndt.name.clone()
    } else {
        Cow::Owned(format!("{}::{}", ndt.module_path, ndt.name))
    }
}

/// Allows configuring the format of the final types file
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub enum Layout {
    /// Produce a Typescript namespace for each Rust module
    Namespaces,
    /// Produce a dedicated file for each Rust module
    Files,
    /// Include the full module path in the types name but keep a flat structure.
    ModulePrefixedName,
    /// Flatten all of the types into a single file of types.
    /// This mode doesn't support having multiple types with the same name.
    #[default]
    FlatFile,
}

impl fmt::Display for Layout {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{self:?}")
    }
}

#[derive(Clone)]
#[allow(clippy::type_complexity)]
struct RuntimeFn(Arc<dyn Fn(FrameworkExporter) -> Result<Cow<'static, str>, Error> + Send + Sync>);

impl fmt::Debug for RuntimeFn {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "RuntimeFn({:p})", self.0)
    }
}

#[derive(Clone)]
#[allow(clippy::type_complexity)]
pub struct BrandedTypeImpl(
    pub(crate)  Arc<
        dyn for<'a> Fn(BrandedTypeExporter<'a>, &Branded) -> Result<Cow<'static, str>, Error>
            + Send
            + Sync,
    >,
);

impl fmt::Debug for BrandedTypeImpl {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "BrandedTypeImpl({:p})", self.0)
    }
}

/// Typescript language exporter.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct Exporter {
    /// Custom header prepended to exported files.
    pub header: Cow<'static, str>,
    raw: Vec<Cow<'static, str>>,
    framework_runtime: Option<RuntimeFn>,
    pub(crate) branded_type_impl: Option<BrandedTypeImpl>,
    framework_prelude: Cow<'static, str>,
    /// Output layout mode for generated TypeScript.
    pub layout: Layout,
    pub(crate) jsdoc: bool,
}

impl Exporter {
    // You should get this from either a [Typescript] or [JSDoc], not construct it directly.
    pub(crate) fn default() -> Exporter {
        Exporter {
            header: Cow::Borrowed(""),
            raw: Vec::new(),
            framework_runtime: None,
            branded_type_impl: None,
            framework_prelude: Cow::Borrowed(
                "// This file has been generated by Specta. Do not edit this file manually.",
            ),
            layout: Default::default(),
            jsdoc: false,
        }
    }

    /// Provide a prelude which is added to the start of all exported files.
    pub fn framework_prelude(mut self, prelude: impl Into<Cow<'static, str>>) -> Self {
        self.framework_prelude = prelude.into();
        self
    }

    /// Add some custom Typescript or Javascript code that is exported as part of the bindings.
    /// It's appending to the types file for single-file layouts or put in a root `index.{ts/js}` for multi-file.
    ///
    /// The closure is wrapped in [`specta::collect()`] to capture any referenced types.
    /// Ensure you call `T::reference()` within the closure if you want an import to be created.
    pub fn framework_runtime(
        mut self,
        builder: impl Fn(FrameworkExporter) -> Result<Cow<'static, str>, Error> + Send + Sync + 'static,
    ) -> Self {
        self.framework_runtime = Some(RuntimeFn(Arc::new(builder)));
        self
    }

    /// Add raw Typescript or Javascript code that is exported as part of the bindings.
    pub fn with_raw(mut self, raw: impl Into<Cow<'static, str>>) -> Self {
        self.raw.push(raw.into());
        self
    }

    /// Configure how `specta_typescript::branded!` types are rendered with exporter context.
    ///
    /// This callback receives both the branded payload and a [`BrandedTypeExporter`], allowing
    /// you to call [`BrandedTypeExporter::inline`] / [`BrandedTypeExporter::reference`] while
    /// preserving the current export configuration.
    ///
    /// # Examples
    ///
    /// `ts-brand` style:
    /// ```rust
    /// # use std::borrow::Cow;
    /// # use specta_typescript::{Branded, Error, Typescript};
    /// let exporter = Typescript::default().branded_type_impl(|ctx, branded| {
    ///     let datatype = ctx.inline(branded.ty())?;
    ///
    ///     Ok(Cow::Owned(format!(
    ///         "import(\"ts-brand\").Brand<{}, \"{}\">",
    ///         datatype,
    ///         branded.brand()
    ///     )))
    /// });
    /// # let _ = exporter;
    /// ```
    ///
    /// Effect style:
    /// ```rust
    /// # use std::borrow::Cow;
    /// # use specta_typescript::{Branded, Error, Typescript};
    /// let exporter = Typescript::default().branded_type_impl(|ctx, branded| {
    ///     let datatype = ctx.inline(branded.ty())?;
    ///
    ///     Ok(Cow::Owned(format!(
    ///         "{} & import(\"effect\").Brand.Brand<\"{}\">",
    ///         datatype,
    ///         branded.brand()
    ///     )))
    /// });
    /// # let _ = exporter;
    /// ```
    pub fn branded_type_impl(
        mut self,
        builder: impl for<'a> Fn(BrandedTypeExporter<'a>, &Branded) -> Result<Cow<'static, str>, Error>
        + Send
        + Sync
        + 'static,
    ) -> Self {
        self.branded_type_impl = Some(BrandedTypeImpl(Arc::new(builder)));
        self
    }

    /// Configure a header for the file.
    ///
    /// This is perfect for configuring lint ignore rules or other file-level comments.
    pub fn header(mut self, header: impl Into<Cow<'static, str>>) -> Self {
        self.header = header.into();
        self
    }

    /// Configure the bindings layout
    pub fn layout(mut self, layout: Layout) -> Self {
        self.layout = layout;
        self
    }

    /// Export the files into a single string.
    ///
    /// Note: This returns an error if the format is `Format::Files`.
    pub fn export(&self, types: &Types, format: impl Format) -> Result<String, Error> {
        fn inner(exporter: Exporter, types: &Types, format: &dyn Format) -> Result<String, Error> {
            let types = format_types(types, &format)?;
            let types = types.as_ref();

            if let Layout::Files = exporter.layout {
                return Err(Error::export_requires_export_to(exporter.layout));
            }
            if let Layout::Namespaces = exporter.layout
                && exporter.jsdoc
            {
                return Err(Error::jsdoc_namespaces_unsupported());
            }

            let mut out = render_file_header(&exporter)?;

            let mut has_manually_exported_user_types = false;
            let mut runtime = Ok(Cow::default());
            if let Some(framework_runtime) = &exporter.framework_runtime {
                runtime = (framework_runtime.0)(FrameworkExporter {
                    exporter: &exporter,
                    format: Some(&format),
                    has_manually_exported_user_types: &mut has_manually_exported_user_types,
                    files_root_types: "",
                    types,
                });
            }
            let runtime = render_runtime(&exporter, runtime?);

            // Framework runtime
            if !runtime.is_empty() {
                out += "\n";
            }
            out += &runtime;
            if !runtime.is_empty() {
                out += "\n";
            }

            // User types (if not included in framework runtime)
            if !has_manually_exported_user_types {
                render_types(&mut out, &exporter, None, types, "")?;
            }

            Ok(out)
        }

        inner(self.clone(), types, &format)
    }

    /// Export the types to a specific file/folder.
    ///
    /// When configured when `format` is `Format::Files`, you must provide a directory path.
    /// Otherwise, you must provide the path of a single file.
    ///
    pub fn export_to(
        &self,
        path: impl AsRef<Path>,
        types: &Types,
        format: impl Format,
    ) -> Result<(), Error> {
        fn inner(
            exporter: Exporter,
            path: &Path,
            types: &Types,
            format: &dyn Format,
        ) -> Result<(), Error> {
            let formatted_types = format_types(types, &format)?;
            let types = formatted_types.as_ref();

            if exporter.layout != Layout::Files {
                let mut result = render_file_header(&exporter)?;

                let mut has_manually_exported_user_types = false;
                let mut runtime = Ok(Cow::default());
                if let Some(framework_runtime) = &exporter.framework_runtime {
                    runtime = (framework_runtime.0)(FrameworkExporter {
                        exporter: &exporter,
                        format: Some(&format),
                        has_manually_exported_user_types: &mut has_manually_exported_user_types,
                        files_root_types: "",
                        types,
                    });
                }
                let runtime = render_runtime(&exporter, runtime?);

                if !runtime.is_empty() {
                    result.push('\n');
                    result.push_str(&runtime);
                    result.push('\n');
                }

                if !has_manually_exported_user_types {
                    render_types(&mut result, &exporter, None, types, "")?;
                }

                if let Some(parent) = path.parent() {
                    std::fs::create_dir_all(parent)
                        .map_err(|source| Error::create_dir(parent.to_path_buf(), source))?;
                };
                std::fs::write(path, result)
                    .map_err(|source| Error::write_file(path.to_path_buf(), source))?;
                return Ok(());
            }

            fn export(
                exporter: &Exporter,
                format: Option<&dyn Format>,
                types: &Types,
                module: &mut Module,
                s: &mut String,
                path: &Path,
                files: &mut HashMap<PathBuf, String>,
            ) -> Result<bool, Error> {
                module.types.sort_by(|a, b| {
                    a.name
                        .cmp(&b.name)
                        .then(a.module_path.cmp(&b.module_path))
                        .then(a.location.cmp(&b.location))
                });
                let (rendered_types_result, referenced_types) =
                    references::with_module_path(module.module_path.as_ref(), || {
                        references::collect_references(|| {
                            let mut rendered = String::new();
                            let exported = render_flat_types(
                                &mut rendered,
                                exporter,
                                format,
                                types,
                                module.types.iter().copied(),
                                "",
                            )?;
                            Ok::<_, Error>((rendered, exported))
                        })
                    });
                let (rendered_types, exported) = rendered_types_result?;

                let import_paths = referenced_types
                    .into_iter()
                    .map(|r| reference_module_path(types, &r))
                    .collect::<Result<Vec<_>, _>>()?
                    .into_iter()
                    .flatten()
                    .filter(|module_path| module_path != module.module_path.as_ref())
                    .collect::<BTreeSet<_>>();
                if !import_paths.is_empty() {
                    s.push('\n');
                    s.push_str(&module_import_block(
                        exporter,
                        module.module_path.as_ref(),
                        &import_paths,
                    ));
                }

                if !import_paths.is_empty() && !rendered_types.is_empty() {
                    s.push('\n');
                }

                s.push_str(&rendered_types);

                for (name, module) in &mut module.children {
                    // This doesn't account for `NamedDataType::requires_reference`
                    // but we keep it for performance.
                    if module.types.is_empty() && module.children.is_empty() {
                        continue;
                    }

                    let mut path = path.join(name);
                    let mut out = render_file_header(exporter)?;

                    let has_types =
                        export(exporter, format, types, module, &mut out, &path, files)?;
                    if has_types {
                        path.set_extension(if exporter.jsdoc { "js" } else { "ts" });
                        files.insert(path, out);
                    }
                }

                Ok(exported != 0)
            }

            let mut files = HashMap::new();
            let mut runtime_path = path.join("index");
            runtime_path.set_extension(if exporter.jsdoc { "js" } else { "ts" });

            let mut root_types = String::new();
            export(
                &exporter,
                None,
                types,
                &mut build_module_graph(types),
                &mut root_types,
                path,
                &mut files,
            )?;

            {
                let mut has_manually_exported_user_types = false;
                let mut framework_runtime = Cow::default();
                let mut runtime_references = HashSet::new();
                if let Some(runtime_fn) = &exporter.framework_runtime {
                    let (runtime_result, referenced_types) =
                        references::with_module_path("", || {
                            references::collect_references(|| {
                                (runtime_fn.0)(FrameworkExporter {
                                    exporter: &exporter,
                                    format: Some(&format),
                                    has_manually_exported_user_types:
                                        &mut has_manually_exported_user_types,
                                    files_root_types: &root_types,
                                    types,
                                })
                            })
                        });
                    framework_runtime = runtime_result?;
                    runtime_references = referenced_types;
                }
                let runtime = render_runtime(&exporter, framework_runtime);

                let should_export_user_types =
                    !has_manually_exported_user_types && !root_types.is_empty();

                if !runtime.is_empty() || should_export_user_types {
                    files.insert(runtime_path, {
                        let mut out = render_file_header(&exporter)?;
                        let mut body = String::new();

                        // Framework runtime
                        if !runtime.is_empty() {
                            body.push_str(&runtime);
                        }

                        // User types (if not included in framework runtime)
                        if should_export_user_types {
                            if !body.is_empty() {
                                body.push('\n');
                            }

                            body.push_str(&root_types);
                        }

                        let import_paths = runtime_references
                            .into_iter()
                            .map(|r| reference_module_path(types, &r))
                            .collect::<Result<Vec<_>, _>>()?
                            .into_iter()
                            .flatten()
                            .filter(|module_path| !module_path.is_empty())
                            .collect::<BTreeSet<_>>();

                        let import_paths = import_paths
                            .into_iter()
                            .filter(|module_path| {
                                !body.contains(&module_import_statement(&exporter, "", module_path))
                            })
                            .collect::<BTreeSet<_>>();

                        if !import_paths.is_empty() {
                            out.push('\n');
                            out.push_str(&module_import_block(&exporter, "", &import_paths));
                        }

                        if !body.is_empty() {
                            out.push('\n');
                            if !import_paths.is_empty() {
                                out.push('\n');
                            }
                            out.push_str(&body);
                        }

                        out
                    });
                }
            }

            match path.metadata() {
                Ok(meta) if !meta.is_dir() => {
                    return Err(Error::expected_directory(path.to_path_buf()));
                }
                Ok(_) => {}
                Err(err) if err.kind() == std::io::ErrorKind::NotFound => {}
                Err(source) => {
                    return Err(Error::metadata(path.to_path_buf(), source));
                }
            }

            for (path, content) in &files {
                if let Some(parent) = path.parent() {
                    std::fs::create_dir_all(parent)
                        .map_err(|source| Error::create_dir(parent.to_path_buf(), source))?;
                }
                std::fs::write(path, content)
                    .map_err(|source| Error::write_file(path.clone(), source))?;
            }

            cleanup_stale_files(path, &files, &exporter)?;

            Ok(())
        }

        inner(self.clone(), path.as_ref(), types, &format)
    }
}

fn reference_module_path(types: &Types, r: &NamedReference) -> Result<Option<String>, Error> {
    match &r.inner {
        NamedReferenceType::Reference { .. } => types
            .get(r)
            .map(|ndt| Some(ndt.module_path.as_ref().to_string()))
            .ok_or_else(|| {
                Error::dangling_named_reference("import resolution".to_string(), format!("{r:?}"))
            }),
        NamedReferenceType::Inline { .. } => Ok(None),
        NamedReferenceType::Recursive(_) => types
            .get(r)
            .map(|ndt| Some(ndt.module_path.as_ref().to_string()))
            .ok_or_else(|| {
                Error::dangling_named_reference("import resolution".to_string(), format!("{r:?}"))
            }),
    }
}

fn format_types<'a>(types: &'a Types, format: &'a dyn Format) -> Result<Cow<'a, Types>, Error> {
    let mapped = format
        .map_types(types)
        .map_err(|err| Error::format("type graph formatter failed", err))?;

    // Bodies are formatted against the pre-format graph, so the results can be
    // computed from a shared borrow of it and applied afterwards. Mapping in a
    // single `iter_mut` pass instead needs the graph to also be readable while
    // it is written, which would force a deep clone of every named datatype.
    let mut bodies = Vec::with_capacity(mapped.len());
    let mut changed = matches!(mapped, Cow::Owned(_));
    let mut error = None;

    for ndt in mapped.into_unsorted_iter() {
        if error.is_some() {
            break;
        }

        let mut path = FormatPath::new(rust_type_path(ndt));
        let mut defaults = Vec::new();
        for (idx, generic) in ndt.generics.iter().enumerate() {
            let Some(default) = generic.default.as_ref() else {
                continue;
            };
            let segment =
                PathSegment::Name(Cow::Owned(format!("<generic_default:{}>", generic.name)));
            match path.with(segment, |path| {
                map_datatype_format(Some(format), &mapped, default, path)
            }) {
                Ok(default) => {
                    if let Cow::Owned(default) = default {
                        changed = true;
                        defaults.push((idx, default));
                    }
                }
                Err(source) => {
                    error = Some(source.with_named_datatype(ndt));
                    break;
                }
            }
        }
        if error.is_some() {
            break;
        }

        let datatype = ndt
            .ty
            .as_ref()
            .map(|datatype| map_datatype_format(Some(format), &mapped, datatype, &mut path))
            .transpose();
        match datatype {
            Ok(datatype) => {
                let datatype = match datatype {
                    Some(Cow::Owned(datatype)) => {
                        changed = true;
                        Some(datatype)
                    }
                    _ => None,
                };
                bodies.push((defaults, datatype));
            }
            Err(source) => error = Some(source.with_named_datatype(ndt)),
        }
    }

    if let Some(error) = error {
        return Err(error);
    }

    // A format that left every body untouched (the identity case, or one that
    // only annotates) needs no owned graph at all: the input is already the
    // finished graph.
    if !changed {
        return Ok(mapped);
    }

    let mut output = mapped.into_owned();
    let mut bodies = bodies.into_iter();
    output.iter_mut(|ndt| {
        let Some((defaults, datatype)) = bodies.next() else {
            return;
        };

        // `to_mut` is only paid for when the format actually rewrote a default.
        for (idx, default) in defaults {
            if let Some(generic) = ndt.generics.to_mut().get_mut(idx) {
                generic.default = Some(default);
            }
        }
        if let Some(datatype) = datatype {
            ndt.ty = Some(datatype);
        }
    });

    Ok(Cow::Owned(output))
}

fn render_runtime(exporter: &Exporter, framework_runtime: Cow<'static, str>) -> String {
    let mut runtime = String::new();

    if !framework_runtime.is_empty() {
        runtime.push_str(&framework_runtime);
    }

    for raw in exporter.raw.iter().filter(|raw| !raw.is_empty()) {
        if !runtime.is_empty() {
            runtime.push('\n');
        }
        runtime.push_str(raw);
    }

    runtime
}

/// Apply `format` to `dt`, descending into its children only where the format
/// left the node unchanged.
///
/// A `Cow::Owned` result is the format's complete rendering of that position:
/// formats which rewrite a container (`specta_serde::Format` maps every field
/// itself) return the whole subtree already mapped, so descending into it would
/// format those nodes a second time. `Cow::Borrowed` means "unchanged", so the
/// children are offered to the format in turn - that is what lets a leaf-only
/// format (say, `u32` -> `str`) reach primitives nested in a struct.
///
/// Each datatype in a named body is therefore formatted exactly once, matching
/// the single-pass contract the other exporters follow.
fn map_datatype_format<'a>(
    format: Option<&'a dyn Format>,
    types: &'a Types,
    dt: &'a DataType,
    path: &mut FormatPath,
) -> Result<Cow<'a, DataType>, Error> {
    if matches!(dt, DataType::Generic(_)) {
        return Ok(Cow::Borrowed(dt));
    }

    // Without a format there is nothing to map, and descending would only
    // rebuild the datatype it was given.
    let Some(format) = format else {
        return Ok(Cow::Borrowed(dt));
    };

    match format.map_type(types, dt) {
        Ok(Cow::Owned(dt)) => Ok(Cow::Owned(dt)),
        Ok(Cow::Borrowed(dt)) => map_datatype_format_children(format, types, dt, path),
        Err(err) => {
            // Formats commonly reject an unresolved generic, so a rejected node
            // is still offered to the format child by child.
            if is_unresolved_generic_format_error(err.as_ref()) && contains_generic_reference(dt)? {
                return map_datatype_format_children(format, types, dt, path);
            }
            Err(Error::format_at(
                "datatype formatter failed",
                path.join(),
                err,
            ))
        }
    }
}

/// Whether `dt` contains an unresolved generic, which formats commonly reject.
fn contains_generic_reference(dt: &DataType) -> Result<bool, Error> {
    Ok(match dt {
        DataType::Primitive(_) => false,
        DataType::List(list) => contains_generic_reference(&list.ty)?,
        DataType::Map(map) => {
            contains_generic_reference(map.key_ty())? || contains_generic_reference(map.value_ty())?
        }
        DataType::Nullable(inner) => contains_generic_reference(inner)?,
        DataType::Struct(strct) => match &strct.fields {
            Fields::Unit => false,
            Fields::Unnamed(unnamed) => unnamed
                .fields
                .iter()
                .filter_map(|field| field.ty.as_ref())
                .try_fold(false, |found, ty| {
                    Ok::<_, Error>(found || contains_generic_reference(ty)?)
                })?,
            Fields::Named(named) => named
                .fields
                .iter()
                .filter_map(|(_, field)| field.ty.as_ref())
                .try_fold(false, |found, ty| {
                    Ok::<_, Error>(found || contains_generic_reference(ty)?)
                })?,
        },
        DataType::Enum(enm) => enm.variants.iter().try_fold(false, |found, (_, variant)| {
            let variant_found = match &variant.fields {
                Fields::Unit => false,
                Fields::Unnamed(unnamed) => unnamed
                    .fields
                    .iter()
                    .filter_map(|field| field.ty.as_ref())
                    .try_fold(false, |found, ty| {
                        Ok::<_, Error>(found || contains_generic_reference(ty)?)
                    })?,
                Fields::Named(named) => named
                    .fields
                    .iter()
                    .filter_map(|(_, field)| field.ty.as_ref())
                    .try_fold(false, |found, ty| {
                        Ok::<_, Error>(found || contains_generic_reference(ty)?)
                    })?,
            };

            Ok::<_, Error>(found || variant_found)
        })?,
        DataType::Tuple(tuple) => tuple.elements.iter().try_fold(false, |found, ty| {
            Ok::<_, Error>(found || contains_generic_reference(ty)?)
        })?,
        DataType::Reference(Reference::Named(reference)) => match &reference.inner {
            NamedReferenceType::Reference { generics, .. } => {
                generics.iter().try_fold(false, |found, (_, dt)| {
                    Ok::<_, Error>(found || contains_generic_reference(dt)?)
                })?
            }
            NamedReferenceType::Inline { .. } => false,
            NamedReferenceType::Recursive(_) => false,
        },
        DataType::Generic(_) => true,
        DataType::Reference(Reference::Opaque(_)) => false,
        DataType::Intersection(types) => types.iter().try_fold(false, |found, ty| {
            Ok::<_, Error>(found || contains_generic_reference(ty)?)
        })?,
    })
}

fn is_unresolved_generic_format_error(err: &(dyn std::error::Error + 'static)) -> bool {
    // The format trait currently erases its concrete error type, so this is the
    // narrowest compatibility fallback available for formatters that reject
    // unresolved generics before child mapping has substituted them.
    err.to_string().contains("Unresolved generic reference")
}

/// Formats the children of a node whose own `map_type` result was `Borrowed`.
///
/// `Cow::Borrowed` means no child changed, so the caller can keep borrowing the
/// node: a format that leaves a subtree untouched never pays to own a copy of
/// it.
fn map_datatype_format_children<'a>(
    format: &'a dyn Format,
    types: &'a Types,
    dt: &'a DataType,
    path: &mut FormatPath,
) -> Result<Cow<'a, DataType>, Error> {
    match dt {
        DataType::Primitive(_) | DataType::Generic(_) => Ok(Cow::Borrowed(dt)),
        DataType::List(list) => Ok(
            match path.with(PathSegment::Static("<list_item>"), |path| {
                map_datatype_format(Some(format), types, &list.ty, path)
            })? {
                Cow::Borrowed(_) => Cow::Borrowed(dt),
                Cow::Owned(ty) => {
                    let mut list = list.clone();
                    list.ty = Box::new(ty);
                    Cow::Owned(DataType::List(list))
                }
            },
        ),
        DataType::Map(map) => {
            let key = path.with(PathSegment::Static("<map_key>"), |path| {
                map_datatype_format(Some(format), types, map.key_ty(), path)
            })?;
            let value = path.with(PathSegment::Static("<map_value>"), |path| {
                map_datatype_format(Some(format), types, map.value_ty(), path)
            })?;
            if matches!((&key, &value), (Cow::Borrowed(_), Cow::Borrowed(_))) {
                return Ok(Cow::Borrowed(dt));
            }
            Ok(Cow::Owned(DataType::Map(Map::new(
                key.into_owned(),
                value.into_owned(),
            ))))
        }
        DataType::Nullable(inner) => Ok(
            match map_datatype_format(Some(format), types, inner, path)? {
                Cow::Borrowed(_) => Cow::Borrowed(dt),
                Cow::Owned(inner) => Cow::Owned(DataType::Nullable(Box::new(inner))),
            },
        ),
        DataType::Struct(strct) => Ok(
            match map_datatype_fields(format, types, &strct.fields, path)? {
                None => Cow::Borrowed(dt),
                Some(changes) => {
                    let mut strct = strct.clone();
                    apply_field_changes(&mut strct.fields, changes);
                    Cow::Owned(DataType::Struct(strct))
                }
            },
        ),
        DataType::Enum(enm) => {
            let mut changed: Option<Vec<(usize, Vec<(usize, DataType)>)>> = None;
            for (idx, (variant_name, variant)) in enm.variants.iter().enumerate() {
                let segment = PathSegment::Name(variant_name.clone());
                if let Some(changes) = path.with(segment, |path| {
                    map_datatype_fields(format, types, &variant.fields, path)
                })? {
                    changed.get_or_insert_with(Vec::new).push((idx, changes));
                }
            }

            Ok(match changed {
                None => Cow::Borrowed(dt),
                Some(changed) => {
                    let mut enm = enm.clone();
                    for (idx, changes) in changed {
                        if let Some((_, variant)) = enm.variants.get_mut(idx) {
                            apply_field_changes(&mut variant.fields, changes);
                        }
                    }
                    Cow::Owned(DataType::Enum(enm))
                }
            })
        }
        DataType::Tuple(tuple) => {
            let mut changed: Option<Vec<(usize, DataType)>> = None;
            for (idx, element) in tuple.elements.iter().enumerate() {
                if let Cow::Owned(element) = path.with(PathSegment::Index(idx), |path| {
                    map_datatype_format(Some(format), types, element, path)
                })? {
                    changed.get_or_insert_with(Vec::new).push((idx, element));
                }
            }

            Ok(match changed {
                None => Cow::Borrowed(dt),
                Some(changed) => {
                    let mut elements = tuple.elements.clone();
                    for (idx, element) in changed {
                        if let Some(slot) = elements.get_mut(idx) {
                            *slot = element;
                        }
                    }
                    Cow::Owned(DataType::Tuple(Tuple::new(elements)))
                }
            })
        }
        DataType::Intersection(elements) => {
            let mut changed: Option<Vec<(usize, DataType)>> = None;
            for (idx, element) in elements.iter().enumerate() {
                if let Cow::Owned(element) =
                    map_datatype_format(Some(format), types, element, path)?
                {
                    changed.get_or_insert_with(Vec::new).push((idx, element));
                }
            }

            Ok(match changed {
                None => Cow::Borrowed(dt),
                Some(changed) => {
                    let mut elements = elements.clone();
                    for (idx, element) in changed {
                        if let Some(slot) = elements.get_mut(idx) {
                            *slot = element;
                        }
                    }
                    Cow::Owned(DataType::Intersection(elements))
                }
            })
        }
        DataType::Reference(Reference::Named(reference)) => {
            let mut changed: Option<Vec<(usize, DataType)>> = None;

            let inline_changed = match &reference.inner {
                NamedReferenceType::Inline { dt: inline, .. } => {
                    match map_datatype_format(Some(format), types, inline, path)? {
                        Cow::Borrowed(_) => None,
                        Cow::Owned(inline) => Some(inline),
                    }
                }
                _ => None,
            };

            let generics = match &reference.inner {
                NamedReferenceType::Reference { generics, .. } => generics.as_slice(),
                _ => &[],
            };
            for (idx, (_, ty)) in generics.iter().enumerate() {
                if let Cow::Owned(ty) = map_datatype_format(Some(format), types, ty, path)? {
                    changed.get_or_insert_with(Vec::new).push((idx, ty));
                }
            }

            if inline_changed.is_none() && changed.is_none() {
                return Ok(Cow::Borrowed(dt));
            }

            let mut reference = reference.clone();
            if let Some(inline) = inline_changed
                && let NamedReferenceType::Inline { dt: slot, .. } = &mut reference.inner
            {
                **slot = inline;
            }
            if let Some(changed) = changed {
                let generics = named_reference_generics_mut(&mut reference);
                for (idx, ty) in changed {
                    if let Some((_, slot)) = generics.get_mut(idx) {
                        *slot = ty;
                    }
                }
            }

            Ok(Cow::Owned(DataType::Reference(Reference::Named(reference))))
        }
        DataType::Reference(Reference::Opaque(reference)) => {
            let Some(branded) = reference.downcast_ref::<Branded>() else {
                return Ok(Cow::Borrowed(dt));
            };

            Ok(
                match map_datatype_format(Some(format), types, branded.ty(), path)? {
                    Cow::Borrowed(_) => Cow::Borrowed(dt),
                    Cow::Owned(ty) => Cow::Owned(
                        Reference::opaque(Branded::new(branded.brand().clone(), ty)).into(),
                    ),
                },
            )
        }
    }
}

/// Location within the datatype currently being formatted, for error messages.
///
/// Segments are pushed and popped on a single stack as the recursion descends,
/// so tracking the path costs no allocation unless a format actually fails.
#[derive(Default)]
struct FormatPath(Vec<PathSegment>);

enum PathSegment {
    Static(&'static str),
    Index(usize),
    Name(Cow<'static, str>),
}

impl FormatPath {
    fn new(root: Cow<'static, str>) -> Self {
        Self(vec![PathSegment::Name(root)])
    }

    fn with<T>(&mut self, segment: PathSegment, f: impl FnOnce(&mut Self) -> T) -> T {
        self.0.push(segment);
        let out = f(self);
        self.0.pop();
        out
    }

    fn join(&self) -> String {
        let mut out = String::new();
        for (idx, segment) in self.0.iter().enumerate() {
            if idx != 0 {
                out.push('.');
            }
            match segment {
                PathSegment::Static(segment) => out.push_str(segment),
                PathSegment::Name(name) => out.push_str(name),
                PathSegment::Index(idx) => {
                    use fmt::Write;
                    let _ = write!(out, "{idx}");
                }
            }
        }
        out
    }
}

fn named_reference_generics_mut(
    reference: &mut NamedReference,
) -> &mut [(specta::datatype::Generic, DataType)] {
    match &mut reference.inner {
        NamedReferenceType::Reference { generics, .. } => generics,
        NamedReferenceType::Inline { .. } | NamedReferenceType::Recursive(_) => &mut [],
    }
}

/// Formats every field type in `fields`, returning the changed ones by index.
///
/// `None` means the format left all of them unchanged, so the caller can keep
/// borrowing the node instead of cloning it.
fn map_datatype_fields(
    format: &dyn Format,
    types: &Types,
    fields: &Fields,
    path: &mut FormatPath,
) -> Result<Option<Vec<(usize, DataType)>>, Error> {
    let mut changed: Option<Vec<(usize, DataType)>> = None;

    match fields {
        Fields::Unit => {}
        Fields::Unnamed(unnamed) => {
            for (idx, field) in unnamed.fields.iter().enumerate() {
                let Some(ty) = field.ty.as_ref() else {
                    continue;
                };
                if let Cow::Owned(ty) = path.with(PathSegment::Index(idx), |path| {
                    map_datatype_format(Some(format), types, ty, path)
                })? {
                    changed.get_or_insert_with(Vec::new).push((idx, ty));
                }
            }
        }
        Fields::Named(named) => {
            for (idx, (name, field)) in named.fields.iter().enumerate() {
                let Some(ty) = field.ty.as_ref() else {
                    continue;
                };
                if let Cow::Owned(ty) = path.with(PathSegment::Name(name.clone()), |path| {
                    map_datatype_format(Some(format), types, ty, path)
                })? {
                    changed.get_or_insert_with(Vec::new).push((idx, ty));
                }
            }
        }
    }

    Ok(changed)
}

fn apply_field_changes(fields: &mut Fields, changes: Vec<(usize, DataType)>) {
    match fields {
        Fields::Unit => {}
        Fields::Unnamed(unnamed) => {
            for (idx, ty) in changes {
                if let Some(field) = unnamed.fields.get_mut(idx) {
                    field.ty = Some(ty);
                }
            }
        }
        Fields::Named(named) => {
            for (idx, ty) in changes {
                if let Some((_, field)) = named.fields.get_mut(idx) {
                    field.ty = Some(ty);
                }
            }
        }
    }
}

