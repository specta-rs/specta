#!/usr/bin/env python3
"""Per-construct ablation measurements for `#[derive(Type)]`.

Generates one throwaway fixture per construct under `bench/scratch/ablate/`,
measures each with the same machinery as `measure.py`, and prints the cost of
every construct plus its delta against the smallest variant in its group.

Usage: bench/ablate.py [--n 200] [--iters 5] [group ...]

Groups: field-type, shape, metadata, generic, field-arg. Run with no group
arguments for all of them. Results are written to
`bench/results/ablation.json`.

`generic` variants put the cost on the monomorphisation side, so they use the
same shape as `bench/derive-inst` (N concrete types, N registrations).
"""

import argparse
import json
import pathlib
import subprocess

import harness

BENCH = harness.BENCH
SCRATCH = BENCH / "scratch" / "ablate"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("groups", nargs="*", default=None)
parser.add_argument("--n", type=int, default=200, help="repetitions per construct")
parser.add_argument("--iters", type=int, default=5)
parser.add_argument("--keep", action="store_true", help="keep generated sources")
args = parser.parse_args()
N = args.n

PREAMBLE = """\
// @generated by bench/ablate.py
#![allow(dead_code, deprecated, non_camel_case_types)]
use serde_shim::SerdeShim;
use specta::Type;
"""

SHARED = """\
/// One shared user type so field-type variants can reference a named type.
#[derive(Type)]
pub struct Shared {
    pub v: u64,
}
"""


def w(*lines):
    return list(lines)


def named_struct(i, fields, attrs=(), field_attrs=(), derives="Type"):
    """A named struct with the given `(name, ty)` fields."""
    out = [f"#[derive({derives})]", *attrs, f"pub struct T{i} {{"]
    for j, (name, ty) in enumerate(fields):
        out += [*[a.format(j=j) for a in field_attrs], f"    pub {name}: {ty},"]
    out.append("}")
    return out


def tuple_struct(i, fields, attrs=()):
    out = ["#[derive(Type)]", *attrs, f"pub struct T{i}("]
    for ty in fields:
        out.append(f"    pub {ty},")
    out.append(");")
    return out


def unit_struct(i):
    return ["#[derive(Type)]", f"pub struct T{i};"]


def enum(i, variants, attrs=(), field_attrs=()):
    out = ["#[derive(Type)]", *attrs, f"pub enum T{i} {{"]
    for name, shape in variants:
        if shape is None:
            out.append(f"    {name},")
        elif isinstance(shape, str):
            out += [*[a.format(j=0) for a in field_attrs], f"    {name}({shape}),"]
        elif isinstance(shape, list) and shape and isinstance(shape[0], str):
            out.append(f"    {name}(")
            for ty in shape:
                out.append(f"        {ty},")
            out.append("    ),")
        else:
            out.append(f"    {name} {{")
            for j, (fname, ty) in enumerate(shape):
                out += [*[a.format(j=j) for a in field_attrs], f"        {fname}: {ty},"]
            out.append("    },")
    out.append("}")
    return out


def repeat(fn):
    out = []
    for i in range(N):
        out += fn(i)
        out.append("")
    return out


FIELD_TYPES = [
    ("u64", "u64"),
    ("nested", "Vec<String>"),
    ("user", "Shared"),
    ("generic", "Option<Vec<u64>>"),
]


def field_type_group():
    variants = {
        "empty": repeat(lambda i: named_struct(i, [])),
        "u64x4": repeat(lambda i: named_struct(i, [(c, "u64") for c in "abcd"])),
        "nestedx4": repeat(
            lambda i: named_struct(i, [(c, "Vec<String>") for c in "abcd"])
        ),
        "userx4": repeat(lambda i: named_struct(i, [(c, "Shared") for c in "abcd"])),
        "option-vec-u64": repeat(
            lambda i: named_struct(i, [(c, "Option<Vec<u64>>") for c in "abcd"])
        ),
        "strx4": repeat(lambda i: named_struct(i, [(c, "String") for c in "abcd"])),
    }
    return "field-type", "empty", variants, True


def shape_group():
    variants = {
        "named-3": repeat(lambda i: named_struct(i, [(c, "u64") for c in "abc"])),
        "named-1": repeat(lambda i: named_struct(i, [("a", "u64")])),
        "tuple-3": repeat(lambda i: tuple_struct(i, ["u64", "u64", "u64"])),
        "newtype": repeat(lambda i: tuple_struct(i, ["u64"])),
        "unit": repeat(lambda i: unit_struct(i)),
        "enum-unit-4": repeat(
            lambda i: enum(i, [("A", None), ("B", None), ("C", None), ("D", None)])
        ),
        "enum-newtype-4": repeat(
            lambda i: enum(i, [(n, "u64") for n in "ABCD"])
        ),
        "enum-tuple-4": repeat(
            lambda i: enum(i, [(n, ["u64", "u64", "u64"]) for n in "ABCD"])
        ),
        "enum-named-4": repeat(
            lambda i: enum(
                i,
                [(n, [("a", "u64"), ("b", "u64"), ("c", "u64")]) for n in "ABCD"],
            )
        ),
    }
    return "shape", "unit", variants, True


def metadata_group():
    one = [("a", "u64")]
    meta = "Type, SerdeShim"

    def struct(attrs=(), field_attrs=(), fields=one):
        return repeat(
            lambda i: named_struct(
                i, fields, attrs=attrs, field_attrs=field_attrs, derives=meta
            )
        )

    variants = {
        "none": struct(),
        "serde-rename-all": struct(attrs=['#[serde(rename_all = "camelCase")]']),
        "serde-rename-field": struct(field_attrs=['#[serde(rename = "renamed{j}")]']),
        "serde-default-field": struct(field_attrs=["#[serde(default)]"]),
        "serde-flatten-field": repeat(
            lambda i: named_struct(
                i,
                [("a", "Option<Shared>")],
                field_attrs=["#[serde(flatten)]"],
                derives=meta,
            )
        ),
        "serde-skip-field": struct(field_attrs=["#[serde(skip)]"]),
        "specta-optional": struct(field_attrs=["#[specta(optional)]"]),
        "docs": struct(
            attrs=["/// Container docs.", "///", "/// Second line."],
            field_attrs=["/// Field docs.", "///", "/// Second line."],
        ),
        "deprecated": struct(
            attrs=['#[deprecated(note = "old")]'],
            field_attrs=['#[deprecated(note = "old")]'],
        ),
        "serde-container-tag": struct(attrs=['#[serde(tag = "type")]']),
    }
    return "metadata", "none", variants, True


def generic_group():
    """Each variant: one generic container, N concrete arguments, N roots."""

    def crate(container, bounds, arity, fields, extra=""):
        out = ["#![allow(dead_code, non_camel_case_types)]", "use specta::{Type, Types};", ""]
        if extra:
            out += [extra, ""]
        generics = ", ".join(f"T{k}" for k in range(arity))
        bound = f": {bounds}" if bounds else ""
        out += [
            "#[derive(Type)]",
            f"pub struct C<{generics}{bound}> {{",
        ]
        for name, ty in fields:
            out.append(f"    pub {name}: {ty},")
        out += ["}", ""]
        for i in range(N):
            out += [
                "#[derive(Type, Clone, Copy)]",
                f"pub struct A{i}(pub u64);",
                "",
            ]
        out += ["#[derive(Type)]", "pub struct Uses {"]
        for i in range(N):
            args = ", ".join(f"A{(i + k) % N}" for k in range(arity))
            out.append(f"    pub f{i}: C<{args}>,")
        out += ["}", ""]
        out.append("pub fn all(types: &mut Types) {")
        for i in range(N):
            args = ", ".join(f"A{(i + k) % N}" for k in range(arity))
            out.append(f"    <C<{args}> as Type>::definition(types);")
        out += ["}", ""]
        return out

    variants = {
        "1param": crate("C", "", 1, [("a", "T0"), ("b", "Vec<T0>")]),
        "2param": crate("C", "", 2, [("a", "T0"), ("b", "T1"), ("c", "Vec<T1>")]),
        "bounded": crate(
            "C", "Clone + Send + Sync", 1, [("a", "T0"), ("b", "Option<T0>")]
        ),
        "unbounded": crate("C", "", 1, [("a", "T0"), ("b", "Option<T0>")]),
        "bare": crate("C", "", 1, [("a", "T0")]),
        "vec": crate("C", "", 1, [("a", "Vec<T0>")]),
        "cheap-vec": crate(
            "C",
            "",
            1,
            [("a", "CheapVec<T0>")],
            extra="""\
/// A hand-written list wrapper: the same `DataType` a `Vec<T>` field resolves
/// to, with a single direct `Type` impl instead of the named-type machinery.
pub struct CheapVec<T>(pub T);

impl<T: Type> Type for CheapVec<T> {
    fn definition(types: &mut Types) -> specta::datatype::DataType {
        let mut list = specta::datatype::List::new(types.define::<T>());
        list.unique = false;
        specta::datatype::DataType::List(list)
    }
}""",
        ),
        "option-vec": crate("C", "", 1, [("a", "Option<Vec<T0>>")]),
    }
    return "generic", "bare", variants, False


FIELD_ARG_PRELUDE = """\
use specta::datatype as __D;
use specta::Type as __T;

pub struct Shared;

impl __T for Shared {
    fn definition(types: &mut specta::Types) -> __D::DataType {
        <u64 as __T>::definition(types)
    }
}

/// The pre-`impl Into<Field>` builder shape: the argument is already a `Field`.
trait PlainField {
    fn field_plain(self, name: &'static str, field: __D::Field) -> Self;
}

impl PlainField for __D::StructBuilder<__D::NamedFields> {
    fn field_plain(self, name: &'static str, field: __D::Field) -> Self {
        self.field(name, field)
    }
}
"""


def field_arg_group():
    """Hand-written equivalents of the derive's field-call shape."""

    def crate(fmt):
        out = [FIELD_ARG_PRELUDE]
        for i in range(N):
            out += [
                f"pub struct H{i} {{",
                "    pub a: u64,",
                "    pub b: u64,",
                "    pub c: String,",
                "    pub d: Vec<String>,",
                "    pub e: Shared,",
                "}",
                "",
                f"impl __T for H{i} {{",
                "    fn definition(types: &mut specta::Types) -> __D::DataType {",
                "        fn build(types: &mut specta::Types) -> __D::DataType {",
                "            __D::Struct::named()",
            ]
            for j, (name, ty) in enumerate(
                [
                    ("a", "u64"),
                    ("b", "u64"),
                    ("c", "String"),
                    ("d", "Vec<String>"),
                    ("e", "Shared"),
                ]
            ):
                call = f'<{ty} as __T>::definition(types)'
                out.append("                " + fmt.format(name=name, call=call))
            out += [
                "                .build()",
                "        }",
                f'        types.define_named("ablate::H{i}", "H{i}", "ablate", "", None, build)',
                "    }",
                "}",
                "",
            ]
        return out

    variants = {
        "into": crate('.field("{name}", {call})'),
        "field-new": crate('.field("{name}", __D::Field::new({call}))'),
        "plain-field": crate('.field_plain("{name}", __D::Field::new({call}))'),
    }
    return "field-arg", "into", variants, False


GROUPS = {
    "field-type": field_type_group,
    "shape": shape_group,
    "metadata": metadata_group,
    "generic": generic_group,
    "field-arg": field_arg_group,
}

CARGO = """[package]
name = "ablate-{name}"
version = "0.0.0"
edition = "2024"
publish = false

[workspace]

[dependencies]
specta = {{ path = "../../../../specta", features = ["derive"] }}
serde-shim = {{ path = "../../../serde-shim" }}

[profile.dev]
debug = false
incremental = false
"""


def write_crate(name, body, with_preamble=True):
    path = SCRATCH / name
    (path / "src").mkdir(parents=True, exist_ok=True)
    (path / "Cargo.toml").write_text(CARGO.format(name=name))
    preamble = PREAMBLE + SHARED if with_preamble else ""
    (path / "src" / "lib.rs").write_text(preamble + "\n" + "\n".join(body) + "\n")
    return path


selected = args.groups or list(GROUPS)
results = {}
for group in selected:
    fn = GROUPS[group]
    group_name, baseline, variants, with_preamble = fn()
    print(f"\n== {group_name} (N={N}) ==")
    print(
        f"{'variant':20} {'bytes':>9} {'tokens':>9} {'expand':>7} "
        f"{'typeck':>7} {'codegen':>7} {'total':>7}  {'Δtypeck':>8} {'Δcodegen':>9}"
    )
    group_results = {}
    for name, body in variants.items():
        crate = f"{group_name}-{name}"
        path = write_crate(crate, body, with_preamble)
        harness.build_deps(path)
        expanded_bytes, expanded_tokens = harness.expand(path)
        passes = harness.time_crate(path, args.iters)
        group_results[name] = {
            "expanded_bytes": expanded_bytes,
            "expanded_tokens": expanded_tokens,
            "passes": passes,
        }
    base = group_results[baseline]["passes"]
    for name, result in group_results.items():
        p = result["passes"]
        dt = (p["type_check_crate"]["min"] - base["type_check_crate"]["min"]) * 1000
        dc = (p["codegen_crate"]["min"] - base["codegen_crate"]["min"]) * 1000
        print(
            f"{name:20} {result['expanded_bytes']:9,} {result['expanded_tokens']:9,} "
            f"{p['expand_crate']['min']:7.3f} {p['type_check_crate']['min']:7.3f} "
            f"{p['codegen_crate']['min']:7.3f} {p['total']['min']:7.3f} "
            f"{dt:+8.1f} {dc:+9.1f}"
        )
    results[group_name] = {"baseline": baseline, "n": N, "variants": group_results}

out = BENCH / "results" / "ablation.json"
out.parent.mkdir(parents=True, exist_ok=True)
# Keep groups from previous invocations so a single-group run does not erase
# the rest of the table.
merged = json.loads(out.read_text()) if out.exists() else {}
merged.update(results)
out.write_text(json.dumps(merged, indent=2) + "\n")

if not args.keep:
    subprocess.run(["rm", "-rf", str(SCRATCH)], check=True)
