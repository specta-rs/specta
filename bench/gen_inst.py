"""Generates the `derive-inst` fixture crate, which measures `#[derive(Type)]`
under many instantiations of generic types.

`derive-perf` has ~1250 derives but almost no generic instantiations, so it
never makes rustc monomorphise `Type::definition` for a concrete `T`. This
fixture is the other half of the picture: a few generic containers, then
`INST` concrete types that use them at different arguments, plus `INST` roots
that call `Type::definition` so the generic body is actually instantiated.
"""

import json
import os
import pathlib

# Number of concrete instantiations. `SCALE=1` gives a quick smoke test.
INST = int(os.environ.get("INST", "200"))

out = []


def w(s=""):
    out.append(s)


w("// @generated by bench/gen_inst.py -- instantiation-heavy `#[derive(Type)]` fixture.")
w("#![allow(dead_code, non_camel_case_types)]")
w()
w("use specta::{Type, Types};")
w()

# The generic containers under test.
w("/// One type parameter, used directly and behind `Vec`.")
w("#[derive(Type)]")
w("pub struct Wrapper<T> {")
w("    pub inner: T,")
w("    pub list: Vec<T>,")
w("}")
w()
w("/// Two type parameters, mixed into the same fields.")
w("#[derive(Type)]")
w("pub struct Pair<T, U> {")
w("    pub a: T,")
w("    pub b: U,")
w("    pub c: Option<T>,")
w("    pub d: Vec<U>,")
w("}")
w()
w("/// An enum container, so variant shapes instantiate too.")
w("#[derive(Type)]")
w("pub enum Choice<T> {")
w("    None,")
w("    One(T),")
w("    Many { items: Vec<T> },")
w("}")
w()
w("/// A bounded container: the bound is part of every instantiation's obligations.")
w("#[derive(Type)]")
w("pub struct Bounded<T: Clone + Send + Sync> {")
w("    pub a: T,")
w("    pub b: Option<T>,")
w("}")
w()

# Concrete arguments. Each is a real user type, so the bound holds and the
# instantiation is a distinct monomorphisation.
for i in range(INST):
    w(f"#[derive(Type, Clone, Copy)]")
    w(f"pub struct A{i}(pub u64);")
    w()

# Instantiations: every `UsesN` mentions five distinct generic applications, so
# its derived `definition` calls into five monomorphisations.
for i in range(INST):
    nxt = (i + 1) % INST
    sev = (i * 7) % INST
    w(f"#[derive(Type)]")
    w(f"pub struct Uses{i} {{")
    w(f"    pub a: Wrapper<A{i}>,")
    w(f"    pub b: Pair<A{i}, A{nxt}>,")
    w(f"    pub c: Choice<A{sev}>,")
    w(f"    pub d: Bounded<A{i}>,")
    w(f"    pub e: Vec<Wrapper<A{i}>>,")
    w("}")
    w()

# Registration roots, like a user's `collect::<Vec<DataType>>()` call would emit.
w("pub fn all(types: &mut Types) {")
for i in range(INST):
    w(f"    <Wrapper<A{i}> as Type>::definition(types);")
w("}")
w()
w("pub fn all_pairs(types: &mut Types) {")
for i in range(INST):
    nxt = (i + 1) % INST
    w(f"    <Pair<A{i}, A{nxt}> as Type>::definition(types);")
w("}")
w()

bench = pathlib.Path(__file__).resolve().parent
src = bench / "derive-inst" / "src"
src.mkdir(parents=True, exist_ok=True)
(src / "lib.rs").write_text("\n".join(out) + "\n")

(bench / "derive-inst" / "Cargo.toml").write_text(
    """[package]
name = "derive-inst"
version = "0.0.0"
edition = "2024"
publish = false

# Standalone workspace so the fixture never joins the repository workspace.
[workspace]

[dependencies]
specta = { path = "../../specta", features = ["derive"] }

[profile.dev]
debug = false
incremental = false
"""
)

# `measure.py` reads this so the numbers can be read per instantiation.
(bench / "derive-inst" / "fixture.json").write_text(
    json.dumps(
        {
            "instantiations": 5 * INST,
            "root_calls": 2 * INST,
            "derives": 2 * INST + 4,
            "scale": {"INST": INST},
        },
        indent=2,
    )
    + "\n"
)

print(f"{len(out)} lines, {INST} instantiations")
