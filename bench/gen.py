"""Generates the `derive-perf` fixture crate used to measure `#[derive(Type)]`."""

import os
import pathlib

SCALE = int(os.environ.get("SCALE", "4"))

out = []


def w(s=""):
    out.append(s)


w("// @generated by bench/gen.py -- benchmark fixture for `#[derive(Type)]`.")
w("#![allow(dead_code, deprecated, non_camel_case_types)]")
w()
w("use serde_shim::SerdeShim;")
w("use specta::Type;")
w()

# Plain named structs, 5 fields each.
for i in range(int(60) * SCALE):
    w(f"/// Documentation for `Plain{i}`.")
    w(f"///")
    w(f"/// A second line of docs so the doc lowering has real input.")
    w(f"#[derive(Type)]")
    w(f"pub struct Plain{i} {{")
    w("    pub id: u64,")
    w("    pub name: String,")
    w("    pub tags: Vec<String>,")
    w("    pub enabled: Option<bool>,")
    w("    pub ratio: f64,")
    w("}")
    w()

# Newtypes and tuple structs.
for i in range(int(40) * SCALE):
    w(f"#[derive(Type)]")
    w(f"pub struct Newtype{i}(pub String);")
    w()
    w(f"#[derive(Type)]")
    w(f"pub struct Tuple{i}(pub String, pub i32, pub Option<Vec<u8>>);")
    w()

# Enums with all four variant shapes.
for i in range(int(40) * SCALE):
    w(f"#[derive(Type)]")
    w(f"pub enum Enum{i} {{")
    w(f"    /// A unit variant.")
    w("    Unit,")
    w("    Newtype(String),")
    w("    Tuple(String, i32, Option<bool>),")
    w("    Named {")
    w("        a: String,")
    w("        b: i32,")
    w("        c: Vec<String>,")
    w("        d: Option<Tuple0>,")
    w("    },")
    w("}")
    w()

# Generic structs.
for i in range(int(40) * SCALE):
    w(f"#[derive(Type)]")
    w(f"pub struct Generic{i}<T, U> {{")
    w("    pub a: T,")
    w("    pub b: Vec<U>,")
    w("    pub c: Option<T>,")
    w("    pub d: U,")
    w("    pub e: std::collections::HashMap<String, T>,")
    w("}")
    w()

# Generic enums, bounded and unbounded.
for i in range(int(20) * SCALE):
    w(f"#[derive(Type)]")
    w(f"pub enum GenericEnum{i}<T, U> {{")
    w("    A(T),")
    w("    B { x: U, y: Vec<T> },")
    w("    C,")
    w("}")
    w()

for i in range(int(10) * SCALE):
    w(f"#[derive(Type)]")
    w(f"pub struct Bounded{i}<T: Clone, U>")
    w("where")
    w("    U: Send + Sync,")
    w("{")
    w("    pub a: T,")
    w("    pub b: U,")
    w("}")
    w()

# Serde metadata heavy types.
for i in range(int(30) * SCALE):
    w(f"#[derive(Type, SerdeShim)]")
    w('#[serde(rename_all = "camelCase", rename_all_fields = "snake_case")]')
    w(f"pub enum SerdeEnum{i} {{")
    w('    #[serde(rename = "firstOne", alias = "one")]')
    w("    First {")
    w('        #[serde(rename = "aField", default)]')
    w("        a_field: String,")
    w('        #[serde(skip_serializing_if = "Option::is_none", flatten)]')
    w("        b: Option<Plain0>,")
    w("        #[serde(skip)]")
    w("        skipped: std::time::Duration,")
    w("    },")
    w("    Second(#[serde(with = \"fmt\")] String),")
    w("    #[serde(skip)]")
    w("    Hidden,")
    w("}")
    w()

w("#[derive(Type, SerdeShim)]")
w('#[serde(tag = "type", content = "data", untagged)]')
w("pub struct SerdeContainer {")
w("    pub a: String,")
w("}")
w()
w("#[derive(Type, SerdeShim)]")
w("#[serde(transparent)]")
w("pub struct Transparent(pub String);")
w()

# Generic with defaults and skip_default_generic.
w("#[derive(Type)]")
w("pub struct WithDefaults<T = String, U = i32> {")
w("    pub a: T,")
w("    pub b: U,")
w("}")
w()
w("#[derive(Type)]")
w("pub struct SkipDefault<#[specta(skip_default_generic)] T = String> {")
w("    pub a: T,")
w("}")
w()

# Field attribute overrides and inlining.
for i in range(int(20) * SCALE):
    w(f"#[derive(Type)]")
    w(f"pub struct Overrides{i} {{")
    w("    #[specta(type = String)]")
    w("    pub a: std::time::Duration,")
    w("    #[specta(optional)]")
    w("    pub b: Option<String>,")
    w(f"    #[specta(inline)]")
    w(f"    pub c: Plain{i},")
    w("    #[deprecated(since = \"1.0.0\", note = \"use `a`\")]")
    w("    pub d: bool,")
    w("}")
    w()

# Deprecated containers.
for i in range(int(10) * SCALE):
    w(f"#[deprecated(note = \"old\")]")
    w(f"#[derive(Type)]")
    w(f"pub struct Deprecated{i} {{ pub a: String }}")
    w()

# Lists / recursive-ish shapes.
w("#[derive(Type)]")
w("pub struct Recursive {")
w("    pub children: Vec<Recursive>,")
w("    pub sibling: Option<Box<Recursive>>,")
w("}")
w()
w("#[derive(Type)]")
w("pub struct BigTuple(pub Plain0, pub Plain1, pub Plain2, pub Plain3, pub Plain4);")
w()
w("#[derive(Type)]")
w("pub struct HasFns {")
w("    pub a: Plain0,")
w("    pub b: Plain1,")
w("    pub c: Plain2,")
w("    pub d: Plain3,")
w("}")
w()

pathlib.Path(__file__).with_name("derive-perf").joinpath("src").mkdir(
    parents=True, exist_ok=True
)
pathlib.Path(__file__).with_name("derive-perf").joinpath("src/lib.rs").write_text(
    "\n".join(out) + "\n"
)
print(f"{len(out)} lines")

pathlib.Path(__file__).with_name("derive-perf").joinpath("Cargo.toml").write_text(
    """[package]
name = "derive-perf"
version = "0.0.0"
edition = "2024"
publish = false

# Standalone workspace so the fixture never joins the repository workspace.
[workspace]

[dependencies]
specta = { path = "../../specta", features = ["derive"] }
serde-shim = { path = "../serde-shim" }

[profile.dev]
debug = false
incremental = false
"""
)
